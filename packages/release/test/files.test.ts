import { describe, expect, it } from "@effect/vitest";
import { Effect, Order, Result } from "effect";

import {
	DependentsPolicy,
	Release,
	ReleaseFiles,
	SemVerStrategy,
	VersionScheme,
	VersionStrategy,
} from "@deltafold/release";
import { memoryFs } from "./__fixtures__/memory-fs.ts";
import { headers, packageWith, ProjectChange, retries } from "./__fixtures__/packages.ts";

const widgets = packageWith("@acme/widgets", ["1.5.2"]);
const react = packageWith("@acme/widgets-react", ["1.5.2"]);

const release = Release.make("widgets", {
	packages: [
		{
			package: widgets,
			files: {
				manifest: "packages/widgets/package.json",
				versions: "packages/widgets/versions",
			},
		},
		{
			package: react,
			files: { manifest: "packages/react/package.json", versions: "packages/react/versions" },
		},
	],
	change: ProjectChange,
	version: SemVerStrategy.make({ bump: (change) => change.metadata.bump }),
	replacements: [
		{
			files: ["packages/widgets/src/**/*.ts", "docs/**/*.md"],
			exclude: ["**/generated/**"],
			match: "@next",
			versionOf: widgets,
		},
		{ files: ["examples/**/*.ts"], match: "@next", versionOf: react },
	],
});

const plan = (() => {
	const result = release.plan({
		packages: [
			{ package: widgets, previous: "1.5.2", changes: [retries, headers] },
			// The header fix ships in both packages; it keeps one identity.
			{ package: react, previous: "1.5.2", changes: [headers] },
		],
	});
	if (Result.isFailure(result)) throw new Error(result.failure.message);

	return result.success;
})();

const pendingRetries = `import { ProjectChange } from "../src/changes.ts";

// Pending until the next release.
export const retries = ProjectChange.make("add-retries", { bump: "minor", area: "api" })\`
	Add a retry limit option.
\`;
`;
const pendingHeaders = `import { ProjectChange } from "../src/changes.ts";
import { headerDocs } from "../docs/links.ts";

export const headers = ProjectChange.make("fix-headers", { bump: "patch", area: "api" })\`
	Escape header values. See \${headerDocs}.
\`;
`;

const workspace = () => ({
	".changes/retries.ts": pendingRetries,
	".changes/headers.ts": pendingHeaders,
	"packages/widgets/package.json": `{\n\t"name": "@acme/widgets",\n\t"version": "1.5.2"\n}\n`,
	"packages/react/package.json": `{\n\t"name": "@acme/widgets-react",\n\t"version": "1.5.2"\n}\n`,
	"packages/widgets/versions/1.5.2.ts": "export const version = undefined;\n",
	"packages/widgets/src/index.ts": "/** @since @next */\nexport const retryLimit = 3;\n",
	"packages/widgets/src/generated/schema.ts": "// @next is reserved here.\n",
	"docs/guide.md": "Available since @next.\n",
});

const options = {
	pending: [".changes/*.ts"],
	previous: [
		{
			package: "@acme/widgets-react",
			version: "1.5.2",
			module: "packages/react/src/history.ts",
			exportName: "v1_5_2",
		},
	],
};

describe("prepare and apply", () => {
	it.effect(
		"copies pending declarations, edits manifests and replacements, then consumes pending modules",
		() => {
			const { files, provide } = memoryFs(workspace());

			return Effect.gen(function* () {
				const prepared = yield* ReleaseFiles.prepare(plan, options);
				expect(
					prepared.edits.map(
						(edit) =>
							`${edit.after === null ? "remove" : edit.before === null ? "create" : "edit"} ${edit.path}`,
					),
				).toEqual([
					"create packages/widgets/versions/1.6.0.ts",
					"create packages/react/versions/1.6.0.ts",
					"edit packages/widgets/package.json",
					"edit packages/react/package.json",
					"edit docs/guide.md",
					"edit packages/widgets/src/index.ts",
					"remove .changes/headers.ts",
					"remove .changes/retries.ts",
				]);
				expect(
					prepared.replacements.map((report) => [
						report.versionOf,
						report.version,
						report.zeroMatches,
					]),
				).toEqual([
					["@acme/widgets", "1.6.0", false],
					["@acme/widgets-react", "1.6.0", true],
				]);

				const applied = yield* ReleaseFiles.apply(prepared);
				expect(applied.removed).toEqual([".changes/headers.ts", ".changes/retries.ts"]);
				expect(files.get("packages/widgets/versions/1.6.0.ts"))
					.toBe(`// Generated by @deltafold/release from pending changes. It is ordinary source.
import { Version } from "deltafold";
import { version as previous } from "./1.5.2.ts";
import { ProjectChange } from "../../../src/changes.ts";
import { headerDocs } from "../../../docs/links.ts";

export const retries = ProjectChange.make("add-retries", { bump: "minor", area: "api" })\`
	Add a retry limit option.
\`;

export const headers = ProjectChange.make("fix-headers", { bump: "patch", area: "api" })\`
	Escape header values. See \${headerDocs}.
\`;

export const version = Version.make("1.6.0", {
	previous,
	changes: [retries, headers],
});
`);
				expect(files.get("packages/react/versions/1.6.0.ts")).toContain(
					`import { v1_5_2 as previous } from "../src/history.ts";`,
				);
				expect(files.get("packages/widgets/package.json")).toContain(`"version": "1.6.0"`);
				expect(files.get("docs/guide.md")).toBe("Available since 1.6.0.\n");
				expect(files.get("packages/widgets/src/index.ts")).toContain("@since 1.6.0");
				expect(files.get("packages/widgets/src/generated/schema.ts")).toContain("@next");
			}).pipe(provide);
		},
	);

	it.effect("refuses a stale plan before writing anything", () => {
		const { files, provide } = memoryFs(workspace());

		return Effect.gen(function* () {
			const prepared = yield* ReleaseFiles.prepare(plan, options);
			files.set("docs/guide.md", "Edited after review: @next.\n");
			files.set(".changes/late.ts", pendingRetries.replace("add-retries", "late"));

			const error = yield* Effect.flip(ReleaseFiles.apply(prepared));
			expect(error).toMatchObject({
				_tag: "StalePlan",
				paths: [".changes/late.ts", "docs/guide.md"],
			});
			expect(files.has("packages/widgets/versions/1.6.0.ts")).toBe(false);
		}).pipe(provide);
	});

	it.effect("restores changed files when a write fails", () => {
		const { files, provide } = memoryFs(workspace(), {
			failWrite: "packages/react/package.json",
		});
		const before = new Map(files);

		return Effect.gen(function* () {
			const prepared = yield* ReleaseFiles.prepare(plan, options);
			const error = yield* Effect.flip(ReleaseFiles.apply(prepared));

			expect(error).toMatchObject({
				_tag: "ApplyFailed",
				path: "packages/react/package.json",
				restored: [
					"packages/widgets/package.json",
					"packages/react/versions/1.6.0.ts",
					"packages/widgets/versions/1.6.0.ts",
				],
				unrestored: [],
			});
			expect(new Map(files)).toEqual(before);
		}).pipe(provide);
	});

	it.effect("reports every preparation problem together", () => {
		const initial: Record<string, string> = {
			...workspace(),
			".changes/retries.ts": `export const retries = ProjectChange.make("add-retries", { bump: "minor", area: "api" })\`x\`;\nconst load = () => import("./other.ts");\n`,
			".changes/stray.ts": `import { ProjectChange } from "../src/changes.ts";\n\nexport const stray = ProjectChange.make("stray", { bump: "patch", area: "docs" })\`Stray.\`;\n`,
			"docs/overlap.md": "@next-tag\n",
		};
		// Without a generated 1.5.2 module, the widgets version has no previous source.
		delete initial["packages/widgets/versions/1.5.2.ts"];
		const { provide } = memoryFs(initial);
		const overlapping = Release.make("widgets", {
			...release.config,
			replacements: [
				{ files: ["docs/overlap.md"], match: "@next", versionOf: widgets },
				{ files: ["docs/overlap.md"], match: "next-tag", versionOf: react },
			],
		});
		const result = overlapping.plan({
			packages: [
				{ package: widgets, previous: "1.5.2", changes: [retries, headers] },
				{ package: react, previous: "1.5.2", changes: [headers] },
			],
		});
		if (Result.isFailure(result)) throw new Error(result.failure.message);

		return Effect.gen(function* () {
			const error = yield* Effect.flip(ReleaseFiles.prepare(result.success, options));
			expect(error._tag).toBe("PrepareError");
			if (error._tag !== "PrepareError") return;
			expect(error.issues.map((entry) => entry.reason)).toEqual([
				"UnsupportedRelocation",
				"UnplannedPending",
				"MissingPreviousSource",
				"MissingSource",
				"ReplacementConflict",
			]);
		}).pipe(provide);
	});
});

const reactRequirement = (range: string) => ({
	dependency: "@acme/widgets",
	dependent: "@acme/widgets-react",
	field: "peerDependencies",
	range,
	manifest: "packages/react/package.json",
	private: false,
});

const planDependents = (input: {
	readonly range: string;
	readonly dependents: DependentsPolicy.Policy;
	readonly reactChanges: ReadonlyArray<typeof headers>;
	readonly unchanged?: "align" | "drift";
}) => {
	const result = release.plan({
		dependents: input.dependents,
		version: SemVerStrategy.make({
			bump: (change) => change.metadata.bump,
			unchanged: input.unchanged ?? "align",
		}),
		requirements: [reactRequirement(input.range)],
		packages: [
			{ package: widgets, previous: "1.5.2", changes: [retries, headers] },
			{ package: react, previous: "1.5.2", changes: input.reactChanges },
		],
	});
	if (Result.isFailure(result)) throw new Error(result.failure.message);

	return result.success;
};

describe("dependency updates", () => {
	const reactManifest = `{\n\t"name": "@acme/widgets-react",\n\t"version": "1.5.2",\n\t"peerDependencies": {\n\t\t"@acme/widgets": "^1.5.0"\n\t}\n}\n`;

	it.effect("edits the dependent's range and records it as release metadata", () => {
		const { files, provide } = memoryFs({
			...workspace(),
			"packages/react/package.json": reactManifest,
		});
		const updated = planDependents({
			range: "^1.5.0",
			dependents: DependentsPolicy.propose({ updateRanges: "always" }),
			reactChanges: [headers],
		});

		return Effect.gen(function* () {
			yield* ReleaseFiles.apply(yield* ReleaseFiles.prepare(updated, options));

			expect(files.get("packages/react/package.json")).toBe(
				reactManifest
					.replace('"version": "1.5.2"', '"version": "1.6.0"')
					.replace("^1.5.0", "^1.6.0"),
			);
			expect(files.get("packages/react/versions/1.6.0.ts")).toContain(
				`export const release = Version.withMetadata(version, {\n\tdependencies: [{"dependency":"@acme/widgets","field":"peerDependencies","from":"^1.5.0","to":"^1.6.0","version":"1.6.0"}],\n});`,
			);
			expect(files.get("packages/widgets/versions/1.6.0.ts")).not.toContain("withMetadata");
		}).pipe(provide);
	});

	it.effect("refuses stale requirements and missing selections", () => {
		const { provide } = memoryFs({
			...workspace(),
			"packages/react/package.json": reactManifest,
		});
		const stale = planDependents({
			range: "^1.4.0",
			dependents: DependentsPolicy.propose({ updateRanges: "always" }),
			reactChanges: [headers],
		});
		const unselected = planDependents({
			range: "1.5.0",
			dependents: DependentsPolicy.explicit(),
			reactChanges: [],
			unchanged: "drift",
		});

		return Effect.gen(function* () {
			const staleError = yield* Effect.flip(ReleaseFiles.prepare(stale, options));
			expect(
				staleError._tag === "PrepareError" &&
					staleError.issues.map((entry) => entry.reason),
			).toEqual(["StaleRequirement"]);
			const unselectedError = yield* Effect.flip(ReleaseFiles.prepare(unselected, options));
			expect(
				unselectedError._tag === "PrepareError" &&
					unselectedError.issues.map((entry) => entry.reason),
			).toEqual(["StaleRequirement", "MissingSelection"]);
		}).pipe(provide);
	});
});

const resolvedWorkspace = () => ({
	...workspace(),
	"packages/react/package.json": `{\n\t"name": "@acme/widgets-react",\n\t"version": "1.5.2",\n\t"peerDependencies": {\n\t\t"@acme/widgets": "^1.5.0"\n\t},\n\t"devDependencies": {\n\t\t"@acme/widgets": "1.5.2"\n\t}\n}\n`,
	"apps/docs/package.json": `{\n\t"name": "@acme/docs-site",\n\t"private": true,\n\t"dependencies": {\n\t\t"@acme/widgets": "^1.0.0"\n\t}\n}\n`,
});

const resolveWidgets = ReleaseFiles.resolve(release, {
	version: SemVerStrategy.make({ bump: (change) => change.metadata.bump, unchanged: "drift" }),
	dependents: DependentsPolicy.propose(),
	manifests: ["apps/*/package.json"],
	packages: [
		{ package: widgets, changes: [retries] },
		{ package: react, changes: [] },
	],
});

describe("resolving input from manifests", () => {
	it.effect(
		"reads previous versions and requirements; dev dependencies edit but never release",
		() => {
			const { provide } = memoryFs(resolvedWorkspace());

			return Effect.gen(function* () {
				const { input } = yield* resolveWidgets;
				expect(
					input.packages.map(
						(selection) => `${selection.package.name}@${selection.previous}`,
					),
				).toEqual(["@acme/widgets@1.5.2", "@acme/widgets-react@1.5.2"]);
				const result = release.plan(input);
				if (Result.isFailure(result)) throw new Error(result.failure.message);
				const resolvedPlan = result.success;

				expect(
					resolvedPlan.versions.map(
						(planned) => `${planned.package}@${planned.version.id}`,
					),
				).toEqual(["@acme/widgets@1.6.0"]);
				expect(
					resolvedPlan.dependents.map(
						(proposal) => `${proposal.dependent}:${proposal.field}:${proposal.action}`,
					),
				).toEqual([
					"@acme/docs-site:dependencies:cross-group",
					"@acme/widgets-react:devDependencies:edit",
					"@acme/widgets-react:peerDependencies:satisfied",
				]);
			}).pipe(provide);
		},
	);

	it.effect("refuses preparation when a resolved manifest or the matched set changed", () => {
		const { files, provide } = memoryFs(resolvedWorkspace());

		return Effect.gen(function* () {
			const { input, snapshot } = yield* resolveWidgets;
			const result = release.plan(input);
			if (Result.isFailure(result)) throw new Error(result.failure.message);
			files.set(
				"apps/docs/package.json",
				files.get("apps/docs/package.json")?.replace("^1.0.0", "^1.1.0") ?? "",
			);
			files.set(
				"apps/site/package.json",
				`{ "name": "@acme/site", "dependencies": { "@acme/widgets": "^1.5.0" } }`,
			);

			const error = yield* Effect.flip(
				ReleaseFiles.prepare(result.success, {
					...options,
					pending: [".changes/retries.ts"],
					snapshot,
				}),
			);
			expect(
				error._tag === "PrepareError" &&
					error.issues.map((entry) => [entry.reason, entry.subjects]),
			).toEqual([
				["StaleSource", ["apps/docs/package.json"]],
				["StaleSource", ["apps/site/package.json"]],
				[
					"StaleRequirement",
					["apps/docs/package.json", "@acme/docs-site", "@acme/widgets", "dependencies"],
				],
			]);
		}).pipe(provide);
	});
});

describe("generated version files", () => {
	it.effect("are named after the version verbatim and record no prerelease state", () => {
		const { files, provide } = memoryFs(workspace());
		const result = release.plan({
			input: { pre: { tag: "beta", continue: false } },
			packages: [
				{ package: widgets, previous: "1.5.2", changes: [retries, headers] },
				{ package: react, previous: "1.5.2", changes: [headers] },
			],
		});
		if (Result.isFailure(result)) throw new Error(result.failure.message);

		return Effect.gen(function* () {
			yield* ReleaseFiles.apply(yield* ReleaseFiles.prepare(result.success, options));
			const generated = files.get("packages/widgets/versions/1.6.0-beta.0.ts") ?? "";

			expect(generated).toContain(`export const version = Version.make("1.6.0-beta.0", {`);
			expect(generated).not.toContain("prerelease");
		}).pipe(provide);
	});

	it.effect("refuses version ids that are not plain file names", () => {
		const identity = VersionScheme.make<string>({
			name: "identity",
			decode: Result.succeed,
			encode: (id) => id,
			order: Order.String,
		});
		const odd = packageWith("@acme/odd", ["../up"]);
		const group = Release.make("odd", {
			packages: [
				{
					package: widgets,
					files: ReleaseFiles.at("packages/widgets", { manifest: "package.json" }),
				},
				{
					package: odd,
					files: ReleaseFiles.at("packages/odd", { manifest: "package.json" }),
				},
			],
			change: ProjectChange,
			version: VersionStrategy.make<object, string>({
				name: "identity",
				scheme: identity,
				calculate: () => ({ version: "9" }),
			}),
		});
		const result = group.plan({
			packages: [
				{
					package: widgets,
					previous: "1.5.2",
					changes: [retries],
					version: "zz/../../../escape",
				},
				{ package: odd, changes: [headers], version: "9" },
			],
		});
		if (Result.isFailure(result)) throw new Error(result.failure.message);
		const { provide } = memoryFs({
			...workspace(),
			"packages/odd/package.json": `{ "version": "../up" }`,
		});

		return Effect.gen(function* () {
			const error = yield* Effect.flip(ReleaseFiles.prepare(result.success, options));
			expect(
				error._tag === "PrepareError"
					? error.issues.filter((entry) => entry.reason === "VersionFileName")
					: [],
			).toMatchObject([
				{ subjects: ["@acme/widgets", "zz/../../../escape"] },
				{ subjects: ["@acme/odd", "../up"] },
			]);
		}).pipe(provide);
	});
});

