import { describe, expect, it } from "@effect/vitest";
import { Effect, Result } from "effect";

import { Release, ReleaseFiles, VersionStrategy } from "@deltafold/release";
import { memoryFs } from "./__fixtures__/memory-fs.ts";
import { headers, packageWith, ProjectChange, retries } from "./__fixtures__/packages.ts";

const widgets = packageWith("@acme/widgets", ["1.5.2"]);
const react = packageWith("@acme/widgets-react", ["1.5.2"]);

const release = Release.make("widgets", {
	packages: [
		{
			package: widgets,
			files: {
				manifest: "packages/widgets/package.json",
				versions: "packages/widgets/versions",
			},
		},
		{
			package: react,
			files: { manifest: "packages/react/package.json", versions: "packages/react/versions" },
		},
	],
	change: ProjectChange,
	version: VersionStrategy.semver({ bump: (change) => change.metadata.bump }),
	replacements: [
		{
			files: ["packages/widgets/src/**/*.ts", "docs/**/*.md"],
			exclude: ["**/generated/**"],
			match: "@next",
			versionOf: widgets,
		},
		{ files: ["examples/**/*.ts"], match: "@next", versionOf: react },
	],
});

const plan = (() => {
	const result = release.plan({
		packages: [
			{ package: widgets, previous: "1.5.2", changes: [retries, headers] },
			// The header fix ships in both packages; it keeps one identity.
			{ package: react, previous: "1.5.2", changes: [headers] },
		],
	});
	if (Result.isFailure(result)) throw new Error(result.failure.message);

	return result.success;
})();

const pendingRetries = `import { ProjectChange } from "../src/changes.ts";

// Pending until the next release.
export const retries = ProjectChange.make("add-retries", { bump: "minor", area: "api" })\`
	Add a retry limit option.
\`;
`;
const pendingHeaders = `import { ProjectChange } from "../src/changes.ts";
import { headerDocs } from "../docs/links.ts";

export const headers = ProjectChange.make("fix-headers", { bump: "patch", area: "api" })\`
	Escape header values. See \${headerDocs}.
\`;
`;

const workspace = () => ({
	".changes/retries.ts": pendingRetries,
	".changes/headers.ts": pendingHeaders,
	"packages/widgets/package.json": `{\n\t"name": "@acme/widgets",\n\t"version": "1.5.2"\n}\n`,
	"packages/react/package.json": `{\n\t"name": "@acme/widgets-react",\n\t"version": "1.5.2"\n}\n`,
	"packages/widgets/versions/1.5.2.ts": "export const version = undefined;\n",
	"packages/widgets/src/index.ts": "/** @since @next */\nexport const retryLimit = 3;\n",
	"packages/widgets/src/generated/schema.ts": "// @next is reserved here.\n",
	"docs/guide.md": "Available since @next.\n",
});

const options = {
	pending: [".changes/*.ts"],
	previous: [
		{
			package: "@acme/widgets-react",
			version: "1.5.2",
			module: "packages/react/src/history.ts",
			exportName: "v1_5_2",
		},
	],
};

describe("prepare and apply", () => {
	it.effect(
		"copies pending declarations, edits manifests and replacements, then consumes pending modules",
		() => {
			const { files, layer } = memoryFs(workspace());

			return Effect.gen(function* () {
				const prepared = yield* ReleaseFiles.prepare(plan, options);
				expect(
					prepared.edits.map(
						(edit) =>
							`${edit.after === null ? "remove" : edit.before === null ? "create" : "edit"} ${edit.path}`,
					),
				).toEqual([
					"create packages/widgets/versions/1.6.0.ts",
					"create packages/react/versions/1.6.0.ts",
					"edit packages/widgets/package.json",
					"edit packages/react/package.json",
					"edit docs/guide.md",
					"edit packages/widgets/src/index.ts",
					"remove .changes/headers.ts",
					"remove .changes/retries.ts",
				]);
				expect(
					prepared.replacements.map((report) => [
						report.versionOf,
						report.version,
						report.zeroMatches,
					]),
				).toEqual([
					["@acme/widgets", "1.6.0", false],
					["@acme/widgets-react", "1.6.0", true],
				]);

				const applied = yield* ReleaseFiles.apply(prepared);
				expect(applied.removed).toEqual([".changes/headers.ts", ".changes/retries.ts"]);
				expect(files.get("packages/widgets/versions/1.6.0.ts"))
					.toBe(`// Generated by @deltafold/release from pending changes. It is ordinary source.
import { Version } from "deltafold";
import { version as previous } from "./1.5.2.ts";
import { ProjectChange } from "../../../src/changes.ts";
import { headerDocs } from "../../../docs/links.ts";

export const retries = ProjectChange.make("add-retries", { bump: "minor", area: "api" })\`
	Add a retry limit option.
\`;

export const headers = ProjectChange.make("fix-headers", { bump: "patch", area: "api" })\`
	Escape header values. See \${headerDocs}.
\`;

export const version = Version.make("1.6.0", {
	previous,
	changes: [retries, headers],
});
`);
				expect(files.get("packages/react/versions/1.6.0.ts")).toContain(
					`import { v1_5_2 as previous } from "../src/history.ts";`,
				);
				expect(files.get("packages/widgets/package.json")).toContain(`"version": "1.6.0"`);
				expect(files.get("docs/guide.md")).toBe("Available since 1.6.0.\n");
				expect(files.get("packages/widgets/src/index.ts")).toContain("@since 1.6.0");
				expect(files.get("packages/widgets/src/generated/schema.ts")).toContain("@next");
			}).pipe(Effect.provide(layer));
		},
	);

	it.effect("refuses a stale plan before writing anything", () => {
		const { files, layer } = memoryFs(workspace());

		return Effect.gen(function* () {
			const prepared = yield* ReleaseFiles.prepare(plan, options);
			files.set("docs/guide.md", "Edited after review: @next.\n");
			files.set(".changes/late.ts", pendingRetries.replace("add-retries", "late"));

			const error = yield* Effect.flip(ReleaseFiles.apply(prepared));
			expect(error).toMatchObject({
				_tag: "StalePlan",
				paths: [".changes/late.ts", "docs/guide.md"],
			});
			expect(files.has("packages/widgets/versions/1.6.0.ts")).toBe(false);
		}).pipe(Effect.provide(layer));
	});

	it.effect("restores changed files when a write fails", () => {
		const { files, layer } = memoryFs(workspace(), {
			failWrite: "packages/react/package.json",
		});
		const before = new Map(files);

		return Effect.gen(function* () {
			const prepared = yield* ReleaseFiles.prepare(plan, options);
			const error = yield* Effect.flip(ReleaseFiles.apply(prepared));

			expect(error).toMatchObject({
				_tag: "ApplyFailed",
				path: "packages/react/package.json",
				restored: [
					"packages/widgets/package.json",
					"packages/react/versions/1.6.0.ts",
					"packages/widgets/versions/1.6.0.ts",
				],
				unrestored: [],
			});
			expect(new Map(files)).toEqual(before);
		}).pipe(Effect.provide(layer));
	});

	it.effect("reports every preparation problem together", () => {
		const initial: Record<string, string> = {
			...workspace(),
			".changes/retries.ts": `export const retries = ProjectChange.make("add-retries", { bump: "minor", area: "api" })\`x\`;\nconst load = () => import("./other.ts");\n`,
			".changes/stray.ts": `import { ProjectChange } from "../src/changes.ts";\n\nexport const stray = ProjectChange.make("stray", { bump: "patch", area: "docs" })\`Stray.\`;\n`,
			"docs/overlap.md": "@next-tag\n",
		};
		// Without a generated 1.5.2 module, the widgets version has no previous source.
		delete initial["packages/widgets/versions/1.5.2.ts"];
		const { layer } = memoryFs(initial);
		const overlapping = Release.make("widgets", {
			...release.config,
			replacements: [
				{ files: ["docs/overlap.md"], match: "@next", versionOf: widgets },
				{ files: ["docs/overlap.md"], match: "next-tag", versionOf: react },
			],
		});
		const result = overlapping.plan({
			packages: [
				{ package: widgets, previous: "1.5.2", changes: [retries, headers] },
				{ package: react, previous: "1.5.2", changes: [headers] },
			],
		});
		if (Result.isFailure(result)) throw new Error(result.failure.message);

		return Effect.gen(function* () {
			const error = yield* Effect.flip(ReleaseFiles.prepare(result.success, options));
			expect(error._tag).toBe("PrepareError");
			if (error._tag !== "PrepareError") return;
			expect(error.issues.map((entry) => entry.reason)).toEqual([
				"UnsupportedRelocation",
				"UnplannedPending",
				"MissingPreviousSource",
				"MissingSource",
				"ReplacementConflict",
			]);
		}).pipe(Effect.provide(layer));
	});
});
